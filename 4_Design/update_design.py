"""
Edit 4_Design/dashboard.html, then run this (double-click or: python update_design.py).
It copies your design to the website, the Android app and the ESP32.
"""
import os

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
html = open(os.path.join(here, "dashboard.html"), encoding="utf-8").read()

targets = {
    "Website": os.path.join(root, "2_Website", "FLARE_Dashboard.html"),
    "Android app": os.path.join(root, "3_Android_App", "app", "src", "main", "assets", "dashboard.html"),
}
for name, path in targets.items():
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8", newline="").write(html)
    print("OK ", name.ljust(12), path)

header = os.path.join(root, "1_ESP32_Code", "FLARE_V2_ESP32", "dashboard_html.h")
open(header, "w", encoding="utf-8").write(
    "// AUTO-GENERATED by 4_Design/update_design.py - edit 4_Design/dashboard.html instead.\n"
    "#pragma once\n#include <pgmspace.h>\n\n"
    'const char DASHBOARD_HTML[] PROGMEM = R"FLAREHTML(' + html + ')FLAREHTML";\n')
print("OK ", "ESP32".ljust(12), header)
print("\nDone. Re-upload the ESP32 sketch and run BUILD_APK.bat to apply everywhere.")
input("Press Enter to close...")
